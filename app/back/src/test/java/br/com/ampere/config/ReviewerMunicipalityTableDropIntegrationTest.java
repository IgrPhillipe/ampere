package br.com.ampere.config;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;

@SpringBootTest
class ReviewerMunicipalityTableDropIntegrationTest {

  @Autowired private ReviewerMunicipalityTableDrop drop;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Test
  void dropsTheTableLeftByTheOldSchemaAndToleratesItsAbsence() {
    jdbcTemplate.execute(
        """
        CREATE TABLE reviewer_municipality (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          reviewer_id bigint NOT NULL REFERENCES app_user(id),
          state varchar(2) NOT NULL,
          municipality varchar(255) NOT NULL,
          CONSTRAINT uk_reviewer_municipality_state_name UNIQUE (state, municipality))
        """);

    drop.run(null);
    drop.run(null);

    assertThat(
            jdbcTemplate.queryForObject(
                "SELECT to_regclass('reviewer_municipality') IS NULL", Boolean.class))
        .isTrue();
  }
}
